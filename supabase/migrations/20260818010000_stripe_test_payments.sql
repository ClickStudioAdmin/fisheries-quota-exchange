create function public.mark_order_paid(
    p_order_id bigint,
    p_checkout_session_id text,
    p_payment_intent_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
begin
    select * into v_order
    from public.orders
    where id = p_order_id
    for update;

    if not found then
        raise exception 'Order not found';
    end if;

    if v_order.status = 'AWAITING_COMPLIANCE'
       and exists (
           select 1
           from public.payments
           where order_id = p_order_id
             and status = 'PAID'
       ) then
        return;
    end if;

    if v_order.status <> 'AWAITING_PAYMENT' then
        raise exception 'Order is not waiting for payment';
    end if;

    update public.orders
    set status = 'AWAITING_COMPLIANCE'
    where id = p_order_id;

    insert into public.payments (
        order_id,
        checkout_session_id,
        payment_intent_id,
        status,
        amount_aud,
        fee_amount_aud
    )
    values (
        p_order_id,
        nullif(trim(p_checkout_session_id), ''),
        nullif(trim(p_payment_intent_id), ''),
        'PAID',
        v_order.amount_aud + v_order.fee_amount_aud,
        v_order.fee_amount_aud
    )
    on conflict (order_id) do update
    set
        checkout_session_id = coalesce(
            excluded.checkout_session_id,
            public.payments.checkout_session_id
        ),
        payment_intent_id = coalesce(
            excluded.payment_intent_id,
            public.payments.payment_intent_id
        ),
        status = 'PAID';

    perform public.write_audit_event(
        'PAYMENT_RECEIVED',
        'order',
        p_order_id,
        jsonb_build_object(
            'provider', 'stripe',
            'checkout_session_id', nullif(trim(p_checkout_session_id), ''),
            'payment_intent_id', nullif(trim(p_payment_intent_id), '')
        )
    );
end;
$$;

revoke all on function public.mark_order_paid(bigint, text, text) from public;
grant execute on function public.mark_order_paid(bigint, text, text) to service_role;

create function public.fail_unpaid_order(
    p_order_id bigint,
    p_payment_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
    v_status text;
begin
    v_status := upper(trim(p_payment_status));

    if v_status not in ('FAILED', 'EXPIRED') then
        raise exception 'Invalid payment status';
    end if;

    select * into v_order
    from public.orders
    where id = p_order_id
    for update;

    if not found then
        return;
    end if;

    if v_order.status <> 'AWAITING_PAYMENT' then
        return;
    end if;

    update public.orders
    set status = 'CANCELLED'
    where id = p_order_id;

    perform public.release_order_reservation(p_order_id);

    update public.payments
    set status = v_status
    where order_id = p_order_id
      and status = 'PENDING';

    perform public.write_audit_event(
        'PAYMENT_FAILED',
        'order',
        p_order_id,
        jsonb_build_object('status', v_status)
    );
end;
$$;

revoke all on function public.fail_unpaid_order(bigint, text) from public;
grant execute on function public.fail_unpaid_order(bigint, text) to service_role;

create or replace function public.insert_simulated_order(
    p_listing_id bigint,
    p_buyer_organisation_id bigint,
    p_unit_price_aud numeric
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_listing public.listings%rowtype;
    v_holding public.quota_holdings%rowtype;
    v_buyer_name text;
    v_available numeric;
    v_amount numeric;
    v_order_id bigint;
    v_status text;
    v_charges boolean;
begin
    select * into v_listing
    from public.listings
    where id = p_listing_id
    for update;

    if not found then
        raise exception 'Listing not found';
    end if;

    if v_listing.status <> 'PUBLISHED' then
        raise exception 'Listing is not available';
    end if;

    if p_buyer_organisation_id = v_listing.organisation_id then
        raise exception 'Buyer and seller must be different organisations';
    end if;

    if p_unit_price_aud is null or p_unit_price_aud <= 0 then
        raise exception 'Price must be greater than zero';
    end if;

    select legal_name into v_buyer_name
    from public.organisations
    where id = p_buyer_organisation_id;

    if v_buyer_name is null then
        raise exception 'Organisation not found';
    end if;

    select * into v_holding
    from public.quota_holdings
    where id = v_listing.holding_id
    for update;

    if not found then
        raise exception 'Holding not found';
    end if;

    v_available := v_holding.quantity - coalesce((
        select sum(r.quantity)
        from public.quota_reservations as r
        where r.holding_id = v_holding.id
          and r.status = 'ACTIVE'
    ), 0);

    if v_listing.quantity > v_available then
        raise exception 'Quota is no longer available';
    end if;

    v_amount := round(v_listing.quantity * p_unit_price_aud, 2);

    if v_amount is null or v_amount <= 0 then
        raise exception 'Order amount must be greater than zero';
    end if;

    select organisations.stripe_charges_enabled
    into v_charges
    from public.organisations as organisations
    where organisations.id = v_listing.organisation_id;

    v_status := case
        when coalesce(v_charges, false) then 'AWAITING_PAYMENT'
        else 'AWAITING_COMPLIANCE'
    end;

    insert into public.orders (
        listing_id,
        holding_id,
        seller_organisation_id,
        buyer_organisation_id,
        offering,
        quantity,
        unit_price_aud,
        amount_aud,
        status,
        seller_name,
        buyer_name,
        fishery_name,
        quota_type_name,
        measurement_kind,
        unit_label,
        created_by_email
    )
    values (
        v_listing.id,
        v_listing.holding_id,
        v_listing.organisation_id,
        p_buyer_organisation_id,
        v_listing.offering,
        v_listing.quantity,
        p_unit_price_aud,
        v_amount,
        v_status,
        v_listing.seller_name,
        v_buyer_name,
        v_listing.fishery_name,
        v_listing.quota_type_name,
        v_listing.measurement_kind,
        v_listing.unit_label,
        public.current_user_email()
    )
    returning id into v_order_id;

    insert into public.quota_reservations (
        order_id,
        listing_id,
        holding_id,
        quantity,
        status
    )
    values (
        v_order_id,
        v_listing.id,
        v_listing.holding_id,
        v_listing.quantity,
        'ACTIVE'
    );

    insert into public.transactions (
        order_id,
        status,
        amount_aud
    )
    values (
        v_order_id,
        'PENDING',
        v_amount
    );

    update public.listings
    set
        status = 'RESERVED',
        unit_price_aud = p_unit_price_aud
    where id = v_listing.id;

    perform public.write_audit_event(
        'ORDER_CREATED',
        'order',
        v_order_id,
        jsonb_build_object(
            'listing_id', v_listing.id,
            'quantity', v_listing.quantity,
            'status', v_status
        )
    );

    perform public.write_audit_event(
        'QUOTA_RESERVED',
        'order',
        v_order_id,
        jsonb_build_object(
            'holding_id', v_listing.holding_id,
            'quantity', v_listing.quantity
        )
    );

    return v_order_id;
end;
$$;

create or replace function public.cancel_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
begin
    select * into v_order
    from public.orders
    where id = p_order_id
    for update;

    if not found then
        raise exception 'Order not found';
    end if;

    if v_order.status not in ('AWAITING_COMPLIANCE', 'AWAITING_PAYMENT') then
        raise exception 'Order cannot be cancelled';
    end if;

    if not public.is_platform_admin()
       and public.user_organisation_role(v_order.buyer_organisation_id) is null then
        raise exception 'You cannot cancel this order';
    end if;

    update public.orders
    set status = 'CANCELLED'
    where id = p_order_id;

    perform public.release_order_reservation(p_order_id);

    update public.payments
    set status = 'EXPIRED'
    where order_id = p_order_id
      and status = 'PENDING';

    perform public.write_audit_event(
        'ORDER_CANCELLED',
        'order',
        p_order_id,
        '{}'::jsonb
    );
end;
$$;

