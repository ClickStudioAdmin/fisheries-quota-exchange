create function public.attach_organisation_stripe_account(
    p_organisation_id bigint,
    p_account_id text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_role text;
    v_existing text;
begin
    v_role := public.user_organisation_role(p_organisation_id);

    if v_role is null or v_role not in ('OWNER', 'ADMIN') then
        raise exception 'You cannot connect payments for that account';
    end if;

    if p_account_id is null or length(trim(p_account_id)) = 0 then
        raise exception 'Stripe account is required';
    end if;

    select stripe_account_id
    into v_existing
    from public.organisations
    where id = p_organisation_id
    for update;

    if not found then
        raise exception 'Organisation not found';
    end if;

    if v_existing is not null and v_existing <> trim(p_account_id) then
        raise exception 'This account is already connected to Stripe';
    end if;

    update public.organisations
    set stripe_account_id = trim(p_account_id)
    where id = p_organisation_id;
end;
$$;

revoke all on function public.attach_organisation_stripe_account(bigint, text) from public;
grant execute on function public.attach_organisation_stripe_account(bigint, text) to authenticated;

