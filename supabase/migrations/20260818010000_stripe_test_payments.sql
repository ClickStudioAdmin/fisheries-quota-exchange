create function public.upsert_order_payment(
    p_order_id bigint,
    p_checkout_session_id text,
    p_payment_intent_id text,
    p_amount_aud numeric,
    p_fee_amount_aud numeric
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
begin
    select * into v_order
    from public.orders
    where id = p_order_id
    for update;

    if not found then
        raise exception 'Order not found';
    end if;

    if v_order.status <> 'AWAITING_PAYMENT' then
        raise exception 'Order is not waiting for payment';
    end if;

    if public.user_organisation_role(v_order.buyer_organisation_id) is null
       and not public.is_platform_admin() then
        raise exception 'You cannot pay this order';
    end if;

    insert into public.payments (
        order_id,
        checkout_session_id,
        payment_intent_id,
        status,
        amount_aud,
        fee_amount_aud
    )
    values (
        p_order_id,
        nullif(trim(p_checkout_session_id), ''),
        nullif(trim(p_payment_intent_id), ''),
        'PENDING',
        p_amount_aud,
        coalesce(p_fee_amount_aud, 0)
    )
    on conflict (order_id) do update
    set
        checkout_session_id = excluded.checkout_session_id,
        payment_intent_id = coalesce(
            excluded.payment_intent_id,
            public.payments.payment_intent_id
        ),
        status = 'PENDING',
        amount_aud = excluded.amount_aud,
        fee_amount_aud = excluded.fee_amount_aud
    where public.payments.status <> 'PAID';
end;
$$;

revoke all on function public.upsert_order_payment(bigint, text, text, numeric, numeric) from public;
grant execute on function public.upsert_order_payment(bigint, text, text, numeric, numeric) to authenticated;

