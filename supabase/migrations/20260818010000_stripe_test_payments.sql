        unique (stripe_account_id);

create function public.protect_organisation_stripe_columns()
returns trigger
language plpgsql
as $$
begin
    if current_user in ('authenticated', 'anon')
       and (
           new.stripe_account_id is distinct from old.stripe_account_id
           or new.stripe_charges_enabled is distinct from old.stripe_charges_enabled
           or new.stripe_payouts_enabled is distinct from old.stripe_payouts_enabled
           or new.stripe_details_submitted is distinct from old.stripe_details_submitted
       ) then
        raise exception 'Stripe status is set by the payment webhook';
    end if;

    return new;
end;
$$;

create trigger organisations_protect_stripe_columns
before update on public.organisations
for each row
execute function public.protect_organisation_stripe_columns();

alter table public.orders
    drop constraint orders_status_check;

alter table public.orders
    add constraint orders_status_check
        check (status in (
            'AWAITING_PAYMENT',
            'AWAITING_COMPLIANCE',
            'AWAITING_TRANSFER',
            'AWAITING_SETTLEMENT',
            'COMPLETED',
            'REJECTED',
            'CANCELLED'
        ));

create table public.payments (
    id bigint generated by default as identity primary key,
    order_id bigint not null unique references public.orders (id) on delete restrict,
    provider text not null default 'stripe',
    checkout_session_id text unique,
    payment_intent_id text,
    status text not null,
    amount_aud numeric(18, 2) not null,
    fee_amount_aud numeric(18, 2) not null default 0,
    currency text not null default 'aud',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint payments_provider_check check (provider = 'stripe'),
    constraint payments_status_check
        check (status in ('PENDING', 'PAID', 'FAILED', 'EXPIRED')),
    constraint payments_amount_check check (amount_aud > 0),
    constraint payments_fee_check check (fee_amount_aud >= 0)
);

create trigger payments_set_updated_at
before update on public.payments
for each row
execute function public.set_updated_at();

create table public.stripe_webhook_events (
    event_id text primary key,
