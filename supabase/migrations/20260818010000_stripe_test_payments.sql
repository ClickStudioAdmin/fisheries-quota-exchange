create policy payments_select
on public.payments
for select
to authenticated
using (
    public.is_platform_admin()
    or exists (
        select 1
        from public.orders as orders
        where orders.id = payments.order_id
          and (
              public.user_organisation_role(orders.buyer_organisation_id) is not null
