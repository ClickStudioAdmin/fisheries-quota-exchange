create function public.order_seller_payment_account(p_order_id bigint)
returns table (
    account_id text,
    charges_enabled boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
begin
    select * into v_order
    from public.orders
    where id = p_order_id;

    if not found then
        return;
    end if;

    if public.user_organisation_role(v_order.buyer_organisation_id) is null
       and not public.is_platform_admin() then
        return;
    end if;

    return query
    select
        organisations.stripe_account_id,
        organisations.stripe_charges_enabled
    from public.organisations as organisations
    where organisations.id = v_order.seller_organisation_id;
end;
$$;

