create table public.platform_admins (
    email text primary key,
    created_at timestamptz not null default now()
);

alter table public.platform_admins enable row level security;

create function public.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.platform_admins as admins
        where admins.email = public.current_user_email()
    )
$$;

revoke all on function public.is_platform_admin() from public;
grant execute on function public.is_platform_admin() to authenticated;

create function public.platform_admin_count()
returns integer
language sql
stable
security definer
set search_path = public
as $$
    select count(*)::integer from public.platform_admins
$$;

revoke all on function public.platform_admin_count() from public;
grant execute on function public.platform_admin_count() to authenticated;

create function public.claim_first_platform_admin()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_email text;
begin
    v_email := public.current_user_email();

    if v_email is null or v_email = '' then
        raise exception 'Not authenticated';
    end if;

    if exists (select 1 from public.platform_admins) then
        raise exception 'A platform admin already exists';
    end if;

    insert into public.platform_admins (email) values (v_email);
end;
$$;

revoke all on function public.claim_first_platform_admin() from public;
grant execute on function public.claim_first_platform_admin() to authenticated;

