create function public.cancel_listing(p_listing_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_org bigint;
    v_status text;
    v_role text;
begin
    select organisation_id, status
    into v_org, v_status
    from public.listings
    where id = p_listing_id;

    if not found then
        raise exception 'Listing not found';
    end if;

    if v_status not in ('PENDING_APPROVAL', 'PUBLISHED') then
        raise exception 'Listing cannot be cancelled';
    end if;

    v_role := public.user_organisation_role(v_org);

    if not public.is_platform_admin()
       and (v_role is null or v_role not in ('OWNER', 'ADMIN')) then
        raise exception 'You cannot cancel this listing';
    end if;

    update public.listings
    set status = 'CANCELLED'
    where id = p_listing_id;
end;
$$;

revoke all on function public.cancel_listing(bigint) from public;
grant execute on function public.cancel_listing(bigint) to authenticated;
