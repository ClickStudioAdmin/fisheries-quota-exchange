create function public.write_order_audit_event(
    p_order_id bigint,
    p_event_type text,
    p_payload jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not public.is_platform_admin()
       and not exists (
           select 1
           from public.orders as o
           where o.id = p_order_id
             and (
                 public.user_organisation_role(o.buyer_organisation_id) is not null
                 or public.user_organisation_role(o.seller_organisation_id) is not null
             )
       )
    then
        raise exception 'Not allowed';
    end if;

    perform public.write_audit_event(
        p_event_type,
        'order',
        p_order_id,
        coalesce(p_payload, '{}'::jsonb)
    );
end;
$$;

revoke all on function public.write_order_audit_event(bigint, text, jsonb) from public;
grant execute on function public.write_order_audit_event(bigint, text, jsonb) to authenticated;

create function public.transfer_party_profile_payload(p_organisation_id bigint, p_jurisdiction_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    select jsonb_build_object(
        'id', o.id,
        'legal_name', o.legal_name,
        'trading_name', o.trading_name,
        'abn', o.abn,
        'entity_kind', o.entity_kind,
        'acn', o.acn,
        'phone', o.phone,
        'mobile', o.mobile,
        'registered_address', o.registered_address,
        'postal_address', o.postal_address,
        'signatories', (
            select coalesce(
                jsonb_agg(
                    jsonb_build_object(
                        'full_name', u.full_name,
                        'role', u.role
                    )
                    order by u.role, u.full_name
                ),
                '[]'::jsonb
            )
            from public.organisation_users as u
            where u.organisation_id = o.id
              and u.role in ('OWNER', 'ADMIN')
        ),
        'profile', (
            select jsonb_build_object(
                'organisation_id', p.organisation_id,
                'jurisdiction_id', p.jurisdiction_id,
                'client_reference', p.client_reference,
                'licence_number', p.licence_number,
                'fishery_symbols', p.fishery_symbols
            )
            from public.organisation_jurisdiction_profiles as p
            where p.organisation_id = o.id
              and p.jurisdiction_id = p_jurisdiction_id
        )
    )
    from public.organisations as o
    where o.id = p_organisation_id;
$$;

create function public.get_transfer_party_profiles(p_order_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
    v_jurisdiction_id bigint;
begin
    select * into v_order
    from public.orders
    where id = p_order_id;

    if not found then
        return null;
    end if;

    if not public.is_platform_admin()
       and public.user_organisation_role(v_order.buyer_organisation_id) is null
       and public.user_organisation_role(v_order.seller_organisation_id) is null
    then
        raise exception 'Not allowed';
    end if;

    select f.jurisdiction_id into v_jurisdiction_id
    from public.quota_holdings as h
    join public.fisheries as f on f.id = h.fishery_id
    where h.id = v_order.holding_id;

    return jsonb_build_object(
        'jurisdiction_id', v_jurisdiction_id,
        'buyer', public.transfer_party_profile_payload(
            v_order.buyer_organisation_id,
            v_jurisdiction_id
        ),
        'seller', public.transfer_party_profile_payload(
            v_order.seller_organisation_id,
            v_jurisdiction_id
        )
    );
end;
$$;

revoke all on function public.transfer_party_profile_payload(bigint, bigint) from public;
revoke all on function public.get_transfer_party_profiles(bigint) from public;
grant execute on function public.get_transfer_party_profiles(bigint) to authenticated;

