create or replace function public.transfer_document_order_id(p_name text)
returns bigint
language plpgsql
immutable
as $$
declare
    v_folder text;
begin
    v_folder := (storage.foldername(p_name))[1];
    if v_folder ~ '^\d+$' then
        return v_folder::bigint;
    end if;
    return null;
end;
$$;

