-- Phase 10: Queensland transfer process.
-- Shared business fields, jurisdiction profiles, versioned form templates,
-- transfer applications/documents, and a private storage bucket.

alter table public.organisations
    add column if not exists entity_kind text,
    add column if not exists acn text,
    add column if not exists phone text,
    add column if not exists mobile text,
    add column if not exists registered_address text,
    add column if not exists postal_address text;

alter table public.organisations
    drop constraint if exists organisations_entity_kind_check;

alter table public.organisations
    add constraint organisations_entity_kind_check
        check (entity_kind is null or entity_kind in ('INDIVIDUAL', 'COMPANY'));

create unique index if not exists organisations_acn_unique
    on public.organisations (acn)
    where acn is not null;

create table if not exists public.organisation_jurisdiction_profiles (
    id bigint generated by default as identity primary key,
    organisation_id bigint not null references public.organisations (id) on delete restrict,
    jurisdiction_id bigint not null references public.jurisdictions (id) on delete restrict,
    client_reference text,
    licence_number text,
    fishery_symbols text,
    extra jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint organisation_jurisdiction_profiles_unique
        unique (organisation_id, jurisdiction_id)
);

create trigger organisation_jurisdiction_profiles_set_updated_at
before update on public.organisation_jurisdiction_profiles
for each row
execute function public.set_updated_at();

alter table public.organisation_jurisdiction_profiles enable row level security;

create policy organisation_jurisdiction_profiles_select
on public.organisation_jurisdiction_profiles
for select
to authenticated
using (
    public.is_platform_admin()
    or public.user_organisation_role(organisation_id) is not null
);

