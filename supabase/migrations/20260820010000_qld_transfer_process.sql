on public.organisation_jurisdiction_profiles
for insert
to authenticated
with check (public.user_organisation_role(organisation_id) in ('OWNER', 'ADMIN'));

create policy organisation_jurisdiction_profiles_update
on public.organisation_jurisdiction_profiles
for update
to authenticated
using (public.user_organisation_role(organisation_id) in ('OWNER', 'ADMIN'))
with check (public.user_organisation_role(organisation_id) in ('OWNER', 'ADMIN'));

