create function public.apply_quota_event(
    p_holding_id bigint,
    p_event_type text,
    p_quantity_delta numeric,
    p_note text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_holding public.quota_holdings%rowtype;
    v_after numeric;
begin
    select * into v_holding
    from public.quota_holdings
    where id = p_holding_id
    for update;

    if not found then
        raise exception 'Holding not found';
    end if;

    v_after := v_holding.quantity + p_quantity_delta;

    if v_after < 0 then
        raise exception 'Quota ledger would be inconsistent';
    end if;

    update public.quota_holdings
    set quantity = v_after
    where id = p_holding_id;

    insert into public.quota_ledger (
        holding_id,
        event_type,
        quantity_delta,
        quantity_after,
        note,
        created_by_email
    )
    values (
        p_holding_id,
        p_event_type,
        p_quantity_delta,
        v_after,
        nullif(trim(p_note), ''),
        public.current_user_email()
    );
end;
$$;

revoke all on function public.apply_quota_event(bigint, text, numeric, text) from public;

create function public.release_order_reservation(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_listing_id bigint;
begin
    update public.quota_reservations
    set
        status = 'RELEASED',
        released_at = now()
    where order_id = p_order_id
      and status = 'ACTIVE'
    returning listing_id into v_listing_id;

    if v_listing_id is null then
        return;
    end if;

    update public.listings
    set status = case
        when expires_at > now() then 'PUBLISHED'
        else 'CANCELLED'
    end
    where id = v_listing_id
      and status = 'RESERVED';
end;
$$;

revoke all on function public.release_order_reservation(bigint) from public;

create or replace function public.create_listing(
    p_holding_id bigint,
    p_offering text,
    p_quantity numeric,
    p_unit_price_aud numeric,
    p_expires_at timestamptz
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_holding public.quota_holdings%rowtype;
    v_role text;
    v_id bigint;
    v_seller text;
    v_fishery text;
    v_stock text;
    v_season text;
    v_quota_type text;
    v_kind text;
    v_unit text;
    v_committed numeric;
begin
    if public.current_user_email() is null then
        raise exception 'Not authenticated';
    end if;

    select * into v_holding
    from public.quota_holdings
    where id = p_holding_id
    for update;

    if not found then
        raise exception 'Holding not found';
    end if;

    v_role := public.user_organisation_role(v_holding.organisation_id);

    if v_role is null or v_role not in ('OWNER', 'ADMIN') then
        raise exception 'You cannot list quota for this organisation';
    end if;

    if p_offering not in ('SALE', 'LEASE') then
        raise exception 'Offering must be SALE or LEASE';
    end if;

    if p_quantity is null or p_quantity <= 0 then
        raise exception 'Quantity must be greater than zero';
    end if;

    v_committed := coalesce((
        select sum(r.quantity)
        from public.quota_reservations as r
        where r.holding_id = p_holding_id
          and r.status = 'ACTIVE'
    ), 0) + coalesce((
        select sum(l.quantity)
        from public.listings as l
        where l.holding_id = p_holding_id
          and l.status in ('PENDING_APPROVAL', 'PUBLISHED')
    ), 0);

    if p_quantity > v_holding.quantity - v_committed then
        raise exception 'Quantity cannot exceed the available holding';
    end if;

    if p_unit_price_aud is null or p_unit_price_aud <= 0 then
        raise exception 'Price must be greater than zero';
    end if;

    if p_expires_at is null or p_expires_at <= now() then
        raise exception 'Expiry must be in the future';
    end if;

    select o.legal_name into v_seller
    from public.organisations as o
    where o.id = v_holding.organisation_id;

    select f.name, st.name, se.name, qt.name, qt.measurement_kind, qt.unit_label
    into v_fishery, v_stock, v_season, v_quota_type, v_kind, v_unit
    from public.stocks as st
    join public.fisheries as f on f.id = st.fishery_id
    join public.seasons as se on se.id = v_holding.season_id
    join public.quota_types as qt on qt.id = v_holding.quota_type_id
    where st.id = v_holding.stock_id;

    insert into public.listings (
        organisation_id,
        holding_id,
        listing_type,
        offering,
        quantity,
        unit_price_aud,
        expires_at,
        status,
        seller_name,
        fishery_name,
        stock_name,
        season_name,
        quota_type_name,
        measurement_kind,
        unit_label,
        created_by_email
    )
    values (
        v_holding.organisation_id,
        p_holding_id,
        'FIXED_PRICE',
        p_offering,
        p_quantity,
        p_unit_price_aud,
        p_expires_at,
        'PENDING_APPROVAL',
        v_seller,
        v_fishery,
        v_stock,
        v_season,
        v_quota_type,
        v_kind,
        v_unit,
        public.current_user_email()
    )
    returning id into v_id;

    return v_id;
end;
$$;

create function public.create_order(
    p_listing_id bigint,
    p_buyer_organisation_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_listing public.listings%rowtype;
    v_holding public.quota_holdings%rowtype;
    v_buyer_name text;
    v_available numeric;
    v_amount numeric;
    v_order_id bigint;
begin
    if public.current_user_email() is null then
        raise exception 'Not authenticated';
    end if;

    if public.user_organisation_role(p_buyer_organisation_id) is null then
        raise exception 'You are not a member of that organisation';
    end if;

    select * into v_listing
    from public.listings
    where id = p_listing_id
    for update;

    if not found then
        raise exception 'Listing not found';
    end if;

    if v_listing.status <> 'PUBLISHED' or v_listing.expires_at <= now() then
        raise exception 'Listing is not available to purchase';
    end if;

    if p_buyer_organisation_id = v_listing.organisation_id then
        raise exception 'You cannot purchase your organisation''s listing';
    end if;

    select legal_name into v_buyer_name
    from public.organisations
    where id = p_buyer_organisation_id;

    if v_buyer_name is null then
        raise exception 'Organisation not found';
    end if;

    select * into v_holding
    from public.quota_holdings
    where id = v_listing.holding_id
    for update;

    if not found then
        raise exception 'Holding not found';
    end if;

    v_available := v_holding.quantity - coalesce((
        select sum(r.quantity)
        from public.quota_reservations as r
        where r.holding_id = v_holding.id
          and r.status = 'ACTIVE'
    ), 0);

    if v_listing.quantity > v_available then
        raise exception 'Quota is no longer available';
    end if;

    v_amount := round(v_listing.quantity * v_listing.unit_price_aud, 2);

    if v_amount is null or v_amount <= 0 then
        raise exception 'Order amount must be greater than zero';
    end if;

    insert into public.orders (
        listing_id,
        holding_id,
        seller_organisation_id,
        buyer_organisation_id,
        offering,
        quantity,
        unit_price_aud,
        amount_aud,
        status,
        seller_name,
        buyer_name,
        fishery_name,
        stock_name,
        season_name,
        quota_type_name,
        measurement_kind,
        unit_label,
        created_by_email
    )
    values (
        v_listing.id,
        v_listing.holding_id,
        v_listing.organisation_id,
        p_buyer_organisation_id,
        v_listing.offering,
        v_listing.quantity,
        v_listing.unit_price_aud,
        v_amount,
        'AWAITING_COMPLIANCE',
        v_listing.seller_name,
        v_buyer_name,
        v_listing.fishery_name,
        v_listing.stock_name,
        v_listing.season_name,
        v_listing.quota_type_name,
        v_listing.measurement_kind,
        v_listing.unit_label,
        public.current_user_email()
    )
    returning id into v_order_id;

    insert into public.quota_reservations (
        order_id,
        listing_id,
        holding_id,
        quantity,
        status
    )
    values (
        v_order_id,
        v_listing.id,
        v_listing.holding_id,
        v_listing.quantity,
        'ACTIVE'
    );

    insert into public.transactions (
        order_id,
        status,
        amount_aud
    )
    values (
        v_order_id,
        'PENDING',
        v_amount
    );

    update public.listings
    set status = 'RESERVED'
    where id = v_listing.id;

    perform public.write_audit_event(
        'ORDER_CREATED',
        'order',
        v_order_id,
        jsonb_build_object(
            'listing_id', v_listing.id,
            'quantity', v_listing.quantity
        )
    );

    perform public.write_audit_event(
        'QUOTA_RESERVED',
        'order',
        v_order_id,
        jsonb_build_object(
            'holding_id', v_listing.holding_id,
            'quantity', v_listing.quantity
        )
    );

    return v_order_id;
end;
$$;

