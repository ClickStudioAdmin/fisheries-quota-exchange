create table public.orders (
    id bigint generated by default as identity primary key,
    listing_id bigint not null references public.listings (id) on delete restrict,
    holding_id bigint not null references public.quota_holdings (id) on delete restrict,
    seller_organisation_id bigint not null references public.organisations (id) on delete restrict,
    buyer_organisation_id bigint not null references public.organisations (id) on delete restrict,
    offering text not null,
    quantity numeric(18, 6) not null,
    unit_price_aud numeric(18, 2) not null,
    amount_aud numeric(18, 2) not null,
    status text not null,
    seller_name text not null,
    buyer_name text not null,
    fishery_name text not null,
    stock_name text not null,
    season_name text not null,
    quota_type_name text not null,
    measurement_kind text not null,
    unit_label text not null,
    created_by_email text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    review_note text,
    constraint orders_offering_check check (offering in ('SALE', 'LEASE')),
    constraint orders_status_check
        check (status in (
            'AWAITING_COMPLIANCE',
            'AWAITING_TRANSFER',
            'AWAITING_SETTLEMENT',
            'COMPLETED',
            'REJECTED',
            'CANCELLED'
        )),
    constraint orders_quantity_check check (quantity > 0),
    constraint orders_price_check check (unit_price_aud > 0),
    constraint orders_amount_check check (amount_aud > 0),
    constraint orders_buyer_seller_check
        check (buyer_organisation_id <> seller_organisation_id)
