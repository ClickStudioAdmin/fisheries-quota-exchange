create function public.simulate_settlement(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.orders%rowtype;
    v_listing public.listings%rowtype;
    v_seller_holding public.quota_holdings%rowtype;
    v_buyer_holding public.quota_holdings%rowtype;
    v_reservation public.quota_reservations%rowtype;
    v_seller_event text;
    v_buyer_event text;
    v_note text;
begin
    if not public.is_platform_admin() then
        raise exception 'Not a platform admin';
    end if;

    select * into v_order
    from public.orders
    where id = p_order_id
    for update;

    if not found then
        raise exception 'Order not found';
    end if;

    if v_order.status <> 'AWAITING_SETTLEMENT' then
        raise exception 'Order is not waiting for settlement';
    end if;

    select * into v_listing
    from public.listings
    where id = v_order.listing_id
    for update;

    if v_listing.status <> 'RESERVED' then
        raise exception 'Listing is not reserved';
    end if;

    select * into v_reservation
    from public.quota_reservations
    where order_id = p_order_id
    for update;

    if v_reservation.status <> 'ACTIVE' then
        raise exception 'Quota reservation is not active';
    end if;

    select * into v_seller_holding
    from public.quota_holdings
    where id = v_order.holding_id
    for update;

    if v_order.offering = 'LEASE' then
        v_seller_event := 'LEASE_OUT';
        v_buyer_event := 'LEASE_IN';
    else
        v_seller_event := 'SALE';
        v_buyer_event := 'PURCHASE';
    end if;

    v_note := 'Order ' || p_order_id::text;

    perform public.apply_quota_event(
        v_seller_holding.id,
        v_seller_event,
        -v_order.quantity,
        v_note
    );

    select * into v_buyer_holding
    from public.quota_holdings
    where organisation_id = v_order.buyer_organisation_id
      and stock_id = v_seller_holding.stock_id
      and season_id = v_seller_holding.season_id
      and quota_type_id = v_seller_holding.quota_type_id
    for update;

    if not found then
        begin
            insert into public.quota_holdings (
                organisation_id,
                stock_id,
                season_id,
                quota_type_id,
                quantity
            )
            values (
                v_order.buyer_organisation_id,
                v_seller_holding.stock_id,
                v_seller_holding.season_id,
                v_seller_holding.quota_type_id,
                0
            )
            returning * into v_buyer_holding;
        exception
            when unique_violation then
                select * into v_buyer_holding
                from public.quota_holdings
                where organisation_id = v_order.buyer_organisation_id
                  and stock_id = v_seller_holding.stock_id
                  and season_id = v_seller_holding.season_id
                  and quota_type_id = v_seller_holding.quota_type_id
                for update;
        end;
    end if;

    perform public.apply_quota_event(
        v_buyer_holding.id,
        v_buyer_event,
        v_order.quantity,
        v_note
    );

    update public.quota_reservations
    set
        status = 'CONSUMED',
        released_at = now()
    where id = v_reservation.id
      and status = 'ACTIVE';

    update public.listings
    set status = 'SOLD'
    where id = v_listing.id
      and status = 'RESERVED';

    update public.orders
    set status = 'COMPLETED'
    where id = p_order_id;

    update public.transactions
    set
